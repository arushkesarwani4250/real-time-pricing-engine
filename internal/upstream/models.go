package upstream

// AuthRequest is the payload sent to authenticate with the upstream WebSocket.
type AuthRequest struct {
	Action string `json:"action"`
	APIKey string `json:"api_key"`
	Secret string `json:"secret"`
}

// SubscribeRequest is the payload sent to subscribe to market price feeds.
type SubscribeRequest struct {
	Action  string   `json:"action"`
	Symbols []string `json:"symbols"`
}

